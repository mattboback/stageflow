import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { computeProjectDiff } from '../../clients/web/app/lib/projects';
import { buildOccurrenceModeReport, splitManualChecks } from '../../clients/web/app/lib/report';
import type { UnifiedReport } from '../../clients/web/app/lib/types/unified-report';
const root = resolve(import.meta.dirname, '../..');
const report: UnifiedReport = JSON.parse(readFileSync(`${root}/clients/web/public/demo/report.json`, 'utf8'));
const baseline: UnifiedReport = JSON.parse(readFileSync(`${root}/clients/web/public/demo/baseline.json`, 'utf8'));
const diff = computeProjectDiff('demo-baseline', baseline, 'demo', report);
const displayed = buildOccurrenceModeReport(splitManualChecks(report).report);
const screenshots = JSON.parse(readFileSync(`${root}/clients/web/public/demo/screenshots.json`, 'utf8')) as {page_id: string; url: string}[];
const newElements = new Set(diff.new.flatMap(i => i.occurrences?.map(o => o.elementId) ?? []));
const expanded = buildOccurrenceModeReport(report);
const newIssueIds = new Set(expanded.issues.filter(i => i.occurrences?.some(o => newElements.has(o.elementId))).map(i => i.id));
// Feature a recognizable form control, not whichever tiny icon happens to be
// first in page order. Keep the screenshot and finding tied to real scan data.
const isFeaturedElement = (element: { issueId: string; ruleId: string; selector?: string }) =>
  newIssueIds.has(element.issueId) && element.ruleId === 'select-name' && element.selector === '#billing-cycle';
const cropPage = expanded.pages.find(p => p.pageOverview?.elements.some(isFeaturedElement));
const cropElement = cropPage?.pageOverview?.elements.find(isFeaturedElement);
if (!cropPage || !cropElement) {
  throw new Error('The demo must capture the new #billing-cycle select-name finding before generating the homepage preview.');
}
const crop = cropPage?.pageOverview && cropElement ? {
  title: expanded.issues.find(i => i.id === cropElement.issueId)?.title ?? cropElement.ruleId,
  issueId: cropElement.issueId,
  screenshot: screenshots.find(s => s.page_id === cropPage.id)?.url ?? '',
  pageWidth: cropPage.pageOverview.pageWidth, pageHeight: cropPage.pageOverview.pageHeight,
  element: cropElement,
} : null;
const summary = {
  pages: report.pages.length, scannersRun: report.scanners.length,
  totalIssues: displayed.issues.length,
  serious: displayed.issues.filter(i => i.severity === 'serious').length,
  moderate: displayed.issues.filter(i => i.severity === 'moderate').length,
  newIssues: diff.delta.newIssues, fixedIssues: diff.delta.fixedIssues,
  unchangedIssues: diff.delta.unchangedIssues,
  baselineScore: baseline.summary.score ?? null, currentScore: report.summary.score ?? null,
  scoreDelta: diff.delta.scoreDelta ?? null,
};
// The home page terminal prints what `stageflow diff` says about these two
// reports, captured from the CLI built from this checkout rather than typed
// out. The CLI diffs `scan --format json` envelopes, so each report is wrapped
// in one. clients/cli/cmd/stageflow/demo_terminal_test.go keeps the capture
// equal to the CLI's output.
function captureDiff() {
  const work = mkdtempSync(join(tmpdir(), 'stageflow-demo-diff-'));
  try {
    const binary = join(work, 'stageflow');
    const build = spawnSync('go', ['build', '-o', binary, './clients/cli/cmd/stageflow'], { cwd: root, encoding: 'utf8' });
    if (build.status !== 0) throw new Error(`go build failed:\n${build.stderr}`);
    for (const [name, doc] of [['baseline.json', baseline], ['current.json', report]] as const) {
      writeFileSync(join(work, name), JSON.stringify({ schema: 'stageflow-cli/report@v1', report: doc }));
    }
    const args = ['diff', 'baseline.json', 'current.json', '--fail-on-new=any'];
    const run = spawnSync(binary, args, { cwd: work, encoding: 'utf8' });
    // 1 is the gate tripping on new findings; anything else is a failed run.
    if (run.status !== 0 && run.status !== 1) throw new Error(`stageflow diff exited ${run.status}:\n${run.stderr}`);
    return { command: `stageflow ${args.join(' ')}`, output: run.stdout.trimEnd(), exitCode: run.status };
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}
writeFileSync(`${root}/clients/web/app/lib/demo/demo-terminal.json`, `${JSON.stringify(captureDiff(), null, '\t')}\n`);
writeFileSync(`${root}/clients/web/app/lib/demo/demo-crop.ts`, `// Generated by just demo-fixture.
import type { PageOverviewElement } from '../types/unified-report';
export const DEMO_CROP: {title: string; issueId: string; screenshot: string; pageWidth: number; pageHeight: number; element: PageOverviewElement} | null = ${JSON.stringify(crop, null, '\t')};
`);
writeFileSync(`${root}/clients/web/app/lib/demo/demo-summary.ts`, `// Generated from real sample-site scans by just demo-fixture.\nexport const DEMO_SUMMARY = ${JSON.stringify(summary, null, '\t')} as const;\n`);
